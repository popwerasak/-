function stick(pz, ground, weight){
  const L = (a, b, c) => `<line x1="${a[0]}" y1="${a[1]}" x2="${b[0]}" y2="${b[1]}" style="stroke:${c}"/>`;
  const far = "var(--muted)", near = "var(--gc, var(--accent))";
  const bottle = w => weight ? `<rect x="${w[0] - 3}" y="${w[1] - 6}" width="6" height="12" rx="2" style="fill:#38bdf8;stroke:none"/>` : "";
  return `<line x1="2" y1="${ground + 2}" x2="118" y2="${ground + 2}" style="stroke:var(--line);stroke-width:2"/>
    <g style="stroke-width:5;stroke-linecap:round;fill:none">
      ${L(pz.p, pz.k2, far)}${L(pz.k2, pz.f2, far)}${L(pz.s, pz.e2, far)}${L(pz.e2, pz.w2, far)}
      ${L(pz.s, pz.p, near)}${L(pz.p, pz.k, near)}${L(pz.k, pz.f, near)}${L(pz.s, pz.e, near)}${L(pz.e, pz.w, near)}
    </g>
    <circle cx="${pz.h[0]}" cy="${pz.h[1]}" r="7" style="fill:var(--card);stroke:${near};stroke-width:4"/>
    ${bottle(pz.w2)}${bottle(pz.w)}`;
}

function poseFig(ex){
  const frame = (pz, label) => `<div class="pf"><svg viewBox="0 0 120 100" role="img" aria-label="${ex.name} ${label}">${stick(pz, ex.ground, ex.weight)}</svg><small>${label}</small></div>`;
  return `<div class="poses">${frame(ex.a, ex.b ? "① ท่าเริ่ม" : "ค้างไว้")}${ex.b ? `<span class="parrow">➜</span>${frame(ex.b, "② ท่าทำ")}` : ""}</div>`;
}

function levelSpans(arr){
  return arr.map((v, i) => `<span class="lv lv${i + 1}">${v}</span>`).join("");
}

